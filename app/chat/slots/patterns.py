"""槽位抽取使用的正则与词表。

集中维护正则，便于复用与单元测试。第一版只用规则 + 正则，不依赖向量库 / LLM。
"""

import re

# 订单号：带前缀（订单号/单号/order 等）后跟 6~24 位字母数字
ORDER_ID_WITH_PREFIX_RE = re.compile(
    r"(?:订单号|订单|单号|order\s*(?:no|id)?|流水号)\s*[:：#]?\s*([A-Za-z0-9]{6,24})",
    re.IGNORECASE,
)
# 订单号：独立出现的 8~24 位（字母）数字串（无前缀场景）
ORDER_ID_BARE_RE = re.compile(r"(?<![A-Za-z0-9])([A-Za-z]?\d{8,24})(?![A-Za-z0-9])")
# 纯订单号匹配（用于判断“整句只发了订单号”），允许 6~24 位字母数字
ORDER_ID_ONLY_RE = re.compile(r"[A-Za-z0-9]{6,24}")

# 中国大陆手机号
PHONE_RE = re.compile(r"(?<!\d)(1[3-9]\d{9})(?!\d)")
# 纯手机号匹配
PHONE_ONLY_RE = re.compile(r"1[3-9]\d{9}")

# 数量：数字 + 量词
QUANTITY_RE = re.compile(r"(\d+)\s*(?:个|件|台|箱|套|双|条|只|份|包)")
# 数量：数量/买 + 数字
QUANTITY_WITH_PREFIX_RE = re.compile(r"(?:数量|买|要|购买|来)\s*(\d+)")

# 颜色词表（第一版枚举常见颜色）
COLOR_WORDS = (
    "红", "橙", "黄", "绿", "青", "蓝", "紫", "黑", "白", "灰", "粉", "金", "银", "棕", "咖啡",
)
# 颜色：颜色词可带“色”
COLOR_RE = re.compile(rf"((?:{'|'.join(COLOR_WORDS)})色?)")

# 商品名（弱规则）：常见动词/指示词后面的名词短语，2~20 个中英文数字字符
# （最少 2 字符：避免「那个啥」「这个呢」把单字虚词抽成商品名）
PRODUCT_NAME_RE = re.compile(
    r"(?:咨询|购买|想买|要买|看看|关于|这款|那款|这个|那个)\s*"
    r"([一-龥A-Za-z0-9]{2,20})"
)

# 商品名（意图词前置模式）：「凉风空调X1多少钱」「小米空调有货吗」——
# 意图关键词前面的名词短语即商品名（v2 修复：无引导词的裸表达是最常见问法）
PRODUCT_BEFORE_INTENT_RE = re.compile(
    r"([一-龥A-Za-z0-9]{2,20}?)\s*"
    r"(?:多少钱|什么价|价格|报价|贵不贵|有货|有没有货|库存|还有吗|缺货|怎么样|参数|规格|配置|详情|介绍)"
)

# 商品名候选的前缀噪声（疑问/礼貌用语与代词），命中后剥离
PRODUCT_PREFIX_NOISE_RE = re.compile(
    r"^(请问|你好|在吗|麻烦问下|麻烦|问下|想问一下|想问|咨询下|帮我看下|那个|这个|这款|那款|一下|就是|，|,|\s)+"
)
# 商品名候选的尾部噪声字符
PRODUCT_SUFFIX_NOISE = "还呢哈啊的了吗现在到底"
